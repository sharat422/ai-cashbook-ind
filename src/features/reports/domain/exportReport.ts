/** Build a spreadsheet-friendly CSV of the report. */
export function buildReportCsv(summary: ReportSummary): string {
  const lines: string[] = [];
  lines.push(`Report,Profit & Loss`);
  lines.push(`From,${summary.from}`);
  lines.push(`To,${summary.to}`);
  lines.push('');
  lines.push('Metric,Amount');
  lines.push(`Income total,${summary.incomeTotal}`);
  lines.push(`Expense total,${summary.expenseTotal}`);
  lines.push(`Net profit,${summary.profit}`);
  lines.push('');
  lines.push('Income category,Amount,Share %');
  for (const r of summary.incomeByCategory) {
    lines.push(`${csv(r.category)},${r.amount},${Math.round(r.share * 100)}`);
  }
  lines.push('');
  lines.push('Expense category,Amount,Share %');
  for (const r of summary.expenseByCategory) {
    lines.push(`${csv(r.category)},${r.amount},${Math.round(r.share * 100)}`);
  }
  return lines.join('\n');
}

function csv(value: string): string {
  return /[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

// --- Excel (.xlsx) ----------------------------------------------------------

/** Rows for the "P&L Summary" sheet (numbers kept numeric for Excel maths). */
export function summaryAoa(summary: ReportSummary): (string | number)[][] {
  const rows: (string | number)[][] = [
    ['Smart CashBook — Profit & Loss'],
    ['Period', `${summary.from} to ${summary.to}`],
    [summary.source === 'local' ? 'Source' : '', summary.source === 'local' ? 'Offline (this device)' : ''],
    [],
    ['Metric', 'Amount (₹)'],
    ['Income total', summary.incomeTotal],
    ['Expense total', summary.expenseTotal],
    ['Net profit', summary.profit],
    [],
    ['Income by category', 'Amount (₹)', 'Share %'],
    ...summary.incomeByCategory.map(r => [r.category, r.amount, Math.round(r.share * 100)]),
    [],
    ['Expense by category', 'Amount (₹)', 'Share %'],
    ...summary.expenseByCategory.map(r => [r.category, r.amount, Math.round(r.share * 100)]),
  ];
  return rows;
}

/** Rows for the "Transactions" sheet — a classic ledger with debit/credit cols. */
export function transactionsAoa(txns: ReportTxn[]): (string | number)[][] {
  const header = ['Date', 'Type', 'Category', 'Vendor / Payer', 'Income (₹)', 'Expense (₹)', 'Notes'];
  const body = txns.map(t => [
    t.date,
    t.type === 'income' ? 'Income' : 'Expense',
    t.category,
    t.party,
    t.type === 'income' ? t.amount : '',
    t.type === 'expense' ? t.amount : '',
    t.notes,
  ]);
  const incomeTotal = txns.filter(t => t.type === 'income').reduce((s, t) => s + t.amount, 0);
  const expenseTotal = txns.filter(t => t.type === 'expense').reduce((s, t) => s + t.amount, 0);
  const totals = ['', '', '', 'Total', incomeTotal, expenseTotal, ''];
  return [header, ...body, totals];
}

/** Build the two-sheet workbook (P&L Summary + Transactions). */
export function buildReportWorkbook(
  summary: ReportSummary,
  txns: ReportTxn[],
): XLSX.WorkBook {
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(summaryAoa(summary)),
    'P&L Summary',
  );
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet(transactionsAoa(txns)),
    'Transactions',
  );
  return wb;
}

/** Serialize the workbook to a base64 string (for RNFS to write to disk). */
export function workbookToBase64(wb: XLSX.WorkBook): string {
  return XLSX.write(wb, {type: 'base64', bookType: 'xlsx'});
}

// --- File + share entry points ---------------------------------------------

/** Render the report (P&L + full transactions) to a PDF and share it. */
export async function exportReportPdf(
  summary: ReportSummary,
  businessName: string,
  txns: ReportTxn[] = [],
): Promise<void> {
  const {filePath} = await RNHTMLtoPDF.convert({
    html: buildReportHtml(summary, businessName, txns),
    fileName: fileStem(summary),
    directory: 'Documents',
  });
  if (!filePath) throw new Error('Could not generate the PDF.');
  await Share.open({
    url: `file://${filePath}`,
    type: 'application/pdf',
    failOnCancel: false,
  });
}

/** Write a real .xlsx (P&L Summary + Transactions sheets) and share it. */
export async function exportReportXlsx(
  summary: ReportSummary,
  txns: ReportTxn[],
): Promise<void> {
  const base64 = workbookToBase64(buildReportWorkbook(summary, txns));
  const path = `${RNFS.DocumentDirectoryPath}/${fileStem(summary)}.xlsx`;
  await RNFS.writeFile(path, base64, 'base64');
  await Share.open({
    url: `file://${path}`,
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    failOnCancel: false,
  });
}

/** Write the report CSV to a file and open the share sheet (for Excel etc.). */
export async function exportReportCsv(summary: ReportSummary): Promise<void> {
  const path = `${RNFS.DocumentDirectoryPath}/${fileStem(summary)}.csv`;
  await RNFS.writeFile(path, buildReportCsv(summary), 'utf8');
  await Share.open({
    url: `file://${path}`,
    type: 'text/csv',
    failOnCancel: false,
  });
}
