import RNHTMLtoPDF from 'react-native-html-to-pdf';
import RNFS from 'react-native-fs';
import Share from 'react-native-share';
import * as XLSX from 'xlsx';

import type {ReportSummary, ReportTxn} from './entities';
import {formatINR} from '@utils/currency';
import {formatDisplayDate} from '@utils/date';

function fileStem(summary: ReportSummary): string {
  return `SmartCashBook_Report_${summary.from}_to_${summary.to}`;
}

function categoryRows(rows: ReportSummary['incomeByCategory']): string {
  if (rows.length === 0) {
    return '<tr><td colspan="3" class="muted">No entries</td></tr>';
  }
  return rows
    .map(
      r => `<tr>
        <td>${escapeHtml(r.category)}</td>
        <td class="num">${formatINR(r.amount)}</td>
        <td class="num">${Math.round(r.share * 100)}%</td>
      </tr>`,
    )
    .join('');
}

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function transactionRowsHtml(txns: ReportTxn[]): string {
  if (txns.length === 0) {
    return '<tr><td colspan="5" class="muted">No transactions in this range</td></tr>';
  }
  return txns
    .map(
      t => `<tr>
        <td>${formatDisplayDate(t.date)}</td>
        <td>${t.type === 'income' ? 'Income' : 'Expense'}</td>
        <td>${escapeHtml(t.category)}${t.party ? ` · ${escapeHtml(t.party)}` : ''}</td>
        <td class="num" style="color:${t.type === 'income' ? '#16A34A' : '#DC2626'}">${
          t.type === 'income' ? '+' : '−'
        }${formatINR(t.amount)}</td>
        <td>${escapeHtml(t.notes)}</td>
      </tr>`,
    )
    .join('');
}

